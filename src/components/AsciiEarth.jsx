import { useEffect, useRef } from 'react'

function AsciiEarth() {
  const earthRef = useRef(null)

  useEffect(() => {
    const earth = earthRef.current
    if (!earth) return

    const W = 72
    const H = 36
    const CELL_ASPECT = 0.55
    const mapRows = `
................................................###########################################........................
............................................##############################........................................
......................................#########################..................................................
..............................#############################......................................................
.........................############################.............................................................
......................#############################.................######........................................
...................############################..................###########......................................
................############################..................#################...................................
.............############################..................#########################..............................
...........###########################...................#############################............................
.........##########################....................#################################..........................
........#########################....................#####################################........................
.......########################....................#########################################......................
......#######################....................#############################################....................
......######################....................###############################################...................
.....#####################....................#################################################..................
.....####################....................###################################################.................
.....###################.....................###################################################.................
.....###################.....................###################################################.................
.....####################....................###################################################.................
.....#####################....................#################################################..................
......######################....................###############################################...................
......#######################....................#############################################....................
.......########################....................#########################################......................
........#########################....................#####################################........................
.........##########################....................#################################..........................
...........###########################...................#############################............................
.............############################..................#########################..............................
................############################..................#################...................................
...................############################..................###########......................................
......................#############################.................######........................................
.........................############################.............................................................
..............................#############################......................................................
......................................#########################..................................................
............................................##############################........................................
................................................###########################################........................`.trim().split('\n')

    const radius = Math.min(W / 2, H / 2) - 1
    let lon = 0

    function render() {
      const lines = []
      for (let y = 0; y < H; y++) {
        let row = ''
        for (let x = 0; x < W; x++) {
          const nx = ((x - W / 2 + 0.5) / radius) * CELL_ASPECT
          const ny = (y - H / 2 + 0.5) / radius
          const r2 = nx * nx + ny * ny
          if (r2 > 1) {
            row += ' '
            continue
          }
          const nz = Math.sqrt(1 - r2)
          const phi = Math.asin(ny)
          const theta = Math.atan2(nx, nz) + lon
          const mx = Math.floor(((theta / (2 * Math.PI)) + 0.5) * W) % W
          const my = Math.floor(((phi / Math.PI) + 0.5) * H)
          const ch = mapRows[my][mx]
          const light = (nz * 0.7 + 0.3)
          if (ch === '#') {
            row += light > 0.6 ? 'M' : light > 0.4 ? 'N' : light > 0.2 ? 'm' : '.'
          } else {
            row += light > 0.6 ? ':' : light > 0.4 ? '.' : ' '
          }
        }
        lines.push(row)
      }
      if (earth) {
        earth.textContent = lines.join('\n')
      }
      lon += 0.008
      requestAnimationFrame(render)
    }

    const animationId = requestAnimationFrame(render)

    return () => {
      cancelAnimationFrame(animationId)
    }
  }, [])

  return (
    <div className="grid place-items-center min-h-[260px]">
      <pre
        ref={earthRef}
        className="text-[12px] leading-[12px] font-mono text-[#bcd7ff] m-0 whitespace-pre"
        aria-hidden="true"
      ></pre>
    </div>
  )
}

export default AsciiEarth

